"""
Shared plotting style + data loading for the figures in docs/images/.

Every figure is generated by its own script in tools/ and every script writes a
light and a dark PNG, because the README serves them through
<picture media="(prefers-color-scheme: dark)">.

Depends only on numpy + matplotlib (requirements-plot.txt) -- nothing here
touches AEDT, so the figures can be regenerated from committed CSVs alone.
"""
