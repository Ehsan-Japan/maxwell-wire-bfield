# Model constants -- must match magnetic_field_wire.py
# ----------------------------------------------------------------------
MU0 = 4e-7 * np.pi
CURRENT = 5.0          # A
WIRE_LENGTH = 50e-3    # m
WIRE_RADIUS_MM = 2.0   # mm
R_START_MM = 3.0       # first point of Extraction_Line
R_END_MM = 20.0        # last point of Extraction_Line

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(REPO, "results")
IMAGES = os.path.join(REPO, "docs", "images")

